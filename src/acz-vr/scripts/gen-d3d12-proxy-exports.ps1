# J-3b4: regenerate src/acz-vr/d3d12_proxy_exports.h (the proxy's export table)
# from the system d3d12.dll export table (read-only `dumpbin /exports`). Every
# export keeps its ordinal and name and is forwarded to the real library by
# absolute path, except D3D12CreateDevice, which maps to the proxy's thin
# wrapper. NONAME exports are forwarded by ordinal. MSVC .def files cannot
# express an absolute-path forwarder (LNK2001), so the table is emitted as
# linker /export directives that d3d12_proxy.cpp includes. The build re-checks
# the linked DLL against the live system DLL (d3d12_proxy_export_check), so a
# Windows update that changes the table fails the build instead of shipping a
# mismatched proxy.
param([string]$System = (Join-Path $env:SystemRoot 'System32\d3d12.dll'),
      [string]$Out = (Join-Path $PSScriptRoot '..\d3d12_proxy_exports.h'),
      [string]$Dumpbin)
$ErrorActionPreference = 'Stop'
if (-not $Dumpbin) {
  $vs = 'C:\Program Files\Microsoft Visual Studio\18\Community\VC\Tools\MSVC'
  $tools = Get-ChildItem $vs | Sort-Object Name | Select-Object -Last 1
  $Dumpbin = Join-Path $tools.FullName 'bin\Hostx64\x64\dumpbin.exe'
}
$target = 'C:\\Windows\\System32\\d3d12'   # C string escaping
$rows = @()
foreach ($line in (& $Dumpbin /exports $System)) {
  if ($line -match '^\s+(\d+)\s+[0-9A-F]+\s+[0-9A-F]{8}\s+(\S+)\s*$') { $rows += [pscustomobject]@{Ordinal=[int]$Matches[1]; Name=$Matches[2]} }
  elseif ($line -match '^\s+(\d+)\s+[0-9A-F]{8}\s+\[NONAME\]\s*$') { $rows += [pscustomobject]@{Ordinal=[int]$Matches[1]; Name=$null} }
}
if (-not ($rows | Where-Object Name -eq 'D3D12CreateDevice')) { throw 'D3D12CreateDevice not found in the system export table' }
$sha = (Get-FileHash -Algorithm SHA256 -LiteralPath $System).Hash.ToLower()
$ver = (Get-Item -LiteralPath $System).VersionInfo.FileVersion
$lines = @('// GENERATED by src/acz-vr/scripts/gen-d3d12-proxy-exports.ps1 - do not edit by hand.',
           "// Source: $System version $ver sha256 $sha",
           '// Every export keeps its system ordinal and name. All but D3D12CreateDevice are',
           '// loader forwarders to C:\Windows\System32\d3d12.dll by absolute path; NONAME',
           '// exports forward by ordinal. Checked against the live system table at build',
           '// time (d3d12_proxy_export_check).',
           '#pragma once')
foreach ($r in ($rows | Sort-Object Ordinal)) {
  if ($r.Name -eq 'D3D12CreateDevice') { $lines += "#pragma comment(linker, `"/export:D3D12CreateDevice=ProxyD3D12CreateDevice,@$($r.Ordinal)`")" }
  elseif ($r.Name) { $lines += "#pragma comment(linker, `"/export:$($r.Name)=$target.$($r.Name),@$($r.Ordinal)`")" }
  else { $lines += "#pragma comment(linker, `"/export:AczVrOrdinal$($r.Ordinal)=$target.#$($r.Ordinal),@$($r.Ordinal),NONAME`")" }
}
Set-Content -LiteralPath $Out -Value $lines -Encoding ascii
"Wrote $($rows.Count) exports to $Out"
